"""
write_local_config.py - generate the per-machine local_config.yaml.

Called by the installer (using the bundled Python) after the wizard has
collected its answers. Doing this in Python rather than in the installer's
own scripting language keeps YAML quoting and URL-encoding of the database
password in one tested place.

    python scripts/write_local_config.py --defaults <config.yaml>
        --answers <answers.json> --out <local_config.yaml>

The answers file holds the database password, so it is deleted as soon as
it has been read. The defaults file supplies every key the wizard does not
ask about. An existing --out file is never overwritten (upgrades must keep
the machine's settings); pass --force to replace it deliberately.
"""

import argparse
import json
import os
import sys
from pathlib import Path
from urllib.parse import quote

import yaml

# answers key -> (config section, config key)
PATH_ANSWERS = {
    "manifests_dir":       ("paths", "manifests_dir"),
    "reports_dir":         ("paths", "reports_dir"),
    "results_dir":         ("paths", "results_dir"),
    "e_drive_report_data": ("paths", "e_drive_report_data"),
    "database":            ("paths", "database"),
}

HEADER = (
    "# Per-machine configuration, generated by the installer.\n"
    "# Contains database credentials: keep it readable only by SYSTEM and\n"
    "# Administrators. Upgrades never overwrite this file.\n"
)


def build_connection_string(answers: dict) -> str:
    """postgresql:// URL with user and password percent-encoded, so a
    password containing @, :, / or % cannot corrupt the URL."""
    user = quote(answers["db_user"], safe="")
    password = quote(answers["db_password"], safe="")
    host = answers.get("db_host") or "localhost"
    port = answers.get("db_port") or "5432"
    name = answers.get("db_name") or "countablelabs"
    return f"postgresql://{user}:{password}@{host}:{port}/{name}"


def apply_answers(config: dict, answers: dict) -> dict:
    config.setdefault("pipeline", {})["database_connection"] = \
        build_connection_string(answers)
    for answer_key, (section, key) in PATH_ANSWERS.items():
        value = answers.get(answer_key)
        if value:
            config.setdefault(section, {})[key] = value
    return config


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--defaults", required=True)
    parser.add_argument("--answers", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    out = Path(args.out)
    answers_path = Path(args.answers)
    try:
        if out.exists() and not args.force:
            print(f"{out} already exists - leaving it unchanged.")
            return 0
        answers = json.loads(answers_path.read_text(encoding="utf-8"))
    finally:
        # Always remove the answers file: it holds the password.
        try:
            os.remove(answers_path)
        except OSError:
            pass

    with open(args.defaults, encoding="utf-8") as f:
        config = yaml.safe_load(f)
    apply_answers(config, answers)

    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        yaml.safe_dump(config, f, default_flow_style=False, sort_keys=False)
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
